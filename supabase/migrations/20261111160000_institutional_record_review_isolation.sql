begin;

-- Approval/reviewer details are separate from portal-visible operational records.
create table public.institutional_record_reviews (
  record_id uuid primary key,
  institution_id uuid not null references public.institutions(id) on delete cascade,
  approval_status text not null default 'not_required'
    check (approval_status in ('not_required','draft','pending','approved','rejected','withdrawn')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  review_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint institutional_record_reviews_record_institution_fk
    foreign key (record_id, institution_id)
    references public.institutional_records(id, institution_id) on delete cascade
);

create index institutional_record_reviews_institution_status_idx
  on public.institutional_record_reviews(institution_id, approval_status, updated_at desc);

alter table public.institutional_record_reviews enable row level security;
revoke all on public.institutional_record_reviews from public, anon;
grant select, insert, update, delete on public.institutional_record_reviews to authenticated;

create policy institutional_record_reviews_owner_admin_select
  on public.institutional_record_reviews for select to authenticated
  using (public.has_institution_role(institution_id, array['owner','admin']::text[]));
create policy institutional_record_reviews_owner_admin_insert
  on public.institutional_record_reviews for insert to authenticated
  with check (public.has_institution_role(institution_id, array['owner','admin']::text[]));
create policy institutional_record_reviews_owner_admin_update
  on public.institutional_record_reviews for update to authenticated
  using (public.has_institution_role(institution_id, array['owner','admin']::text[]))
  with check (public.has_institution_role(institution_id, array['owner','admin']::text[]));
create policy institutional_record_reviews_owner_admin_delete
  on public.institutional_record_reviews for delete to authenticated
  using (public.has_institution_role(institution_id, array['owner','admin']::text[]));

-- Preserve every historical review value before removing the old columns.
insert into public.institutional_record_reviews (
  record_id, institution_id, approval_status, reviewed_by, reviewed_at, review_notes, created_at, updated_at
)
select id, institution_id, approval_status, reviewed_by, reviewed_at, review_notes, created_at, updated_at
from public.institutional_records
on conflict (record_id) do update set
  institution_id = excluded.institution_id,
  approval_status = excluded.approval_status,
  reviewed_by = excluded.reviewed_by,
  reviewed_at = excluded.reviewed_at,
  review_notes = excluded.review_notes,
  updated_at = excluded.updated_at;

-- Reviewer identity/time are generated by the database, not trusted from a client payload.
create or replace function private.guard_institutional_record_review()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  if tg_op = 'INSERT' then
    if new.approval_status in ('approved','rejected') then
      new.reviewed_by := (select auth.uid());
      new.reviewed_at := now();
    else
      new.reviewed_by := null;
      new.reviewed_at := null;
    end if;
    new.created_at := coalesce(new.created_at, now());
  elsif old.approval_status is distinct from new.approval_status then
    if new.approval_status in ('approved','rejected') then
      new.reviewed_by := (select auth.uid());
      new.reviewed_at := now();
    else
      new.reviewed_by := null;
      new.reviewed_at := null;
    end if;
  else
    new.reviewed_by := old.reviewed_by;
    new.reviewed_at := old.reviewed_at;
  end if;

  new.updated_at := now();
  return new;
end;
$function$;
revoke all on function private.guard_institutional_record_review() from public, anon, authenticated;
create trigger institutional_record_reviews_guard
  before insert or update on public.institutional_record_reviews
  for each row execute function private.guard_institutional_record_review();

-- Preserve review decisions in the existing administrator-only audit stream.
create or replace function private.audit_institutional_record_review()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_module_key text;
  v_record_type text;
begin
  select r.module_key, r.record_type
    into v_module_key, v_record_type
  from public.institutional_records r
  where r.id = new.record_id and r.institution_id = new.institution_id;

  if not found then
    raise exception 'The reviewed institutional record no longer exists' using errcode = '23503';
  end if;

  insert into public.institutional_audit_events (
    institution_id, record_id, module_key, record_type, action,
    old_values, new_values, actor_id
  ) values (
    new.institution_id, new.record_id, v_module_key, v_record_type,
    lower(tg_op),
    case when tg_op = 'UPDATE' then to_jsonb(old) else null end,
    to_jsonb(new),
    (select auth.uid())
  );
  return new;
end;
$function$;
revoke all on function private.audit_institutional_record_review() from public, anon, authenticated;
create trigger institutional_record_reviews_audit
  after insert or update on public.institutional_record_reviews
  for each row execute function private.audit_institutional_record_review();

-- Owner/admin record saves and review state are committed atomically.
create or replace function public.save_institutional_record_with_review(
  p_record_id uuid,
  p_institution_id uuid,
  p_module_key text,
  p_record_type text,
  p_title text,
  p_reference_code text,
  p_description text,
  p_status text,
  p_approval_status text,
  p_visibility text,
  p_record_date date,
  p_due_date date,
  p_amount numeric,
  p_quantity numeric,
  p_payload jsonb,
  p_campus_id uuid
)
returns public.institutional_records
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_user_id uuid := (select auth.uid());
  v_record public.institutional_records;
begin
  if v_user_id is null then
    raise exception 'Authentication is required' using errcode = '42501';
  end if;
  if not public.has_institution_role(p_institution_id, array['owner','admin']::text[]) then
    raise exception 'Only institution owners and administrators may save approval workflow records' using errcode = '42501';
  end if;
  if p_approval_status is null or p_approval_status not in ('not_required','draft','pending','approved','rejected','withdrawn') then
    raise exception 'Invalid approval status' using errcode = '22023';
  end if;
  if nullif(btrim(p_title), '') is null then
    raise exception 'A record title is required' using errcode = '22023';
  end if;
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Record details must be a JSON object' using errcode = '22023';
  end if;

  if p_record_id is null then
    insert into public.institutional_records (
      institution_id, campus_id, module_key, record_type, title, reference_code,
      description, status, visibility, record_date, due_date, amount, quantity,
      payload, created_by, updated_by
    ) values (
      p_institution_id, p_campus_id, p_module_key, p_record_type, btrim(p_title), p_reference_code,
      p_description, p_status, p_visibility, p_record_date, p_due_date, p_amount, p_quantity,
      p_payload, v_user_id, v_user_id
    )
    returning * into v_record;
  else
    update public.institutional_records
    set campus_id = p_campus_id,
        module_key = p_module_key,
        record_type = p_record_type,
        title = btrim(p_title),
        reference_code = p_reference_code,
        description = p_description,
        status = p_status,
        visibility = p_visibility,
        record_date = p_record_date,
        due_date = p_due_date,
        amount = p_amount,
        quantity = p_quantity,
        payload = p_payload,
        updated_by = v_user_id,
        updated_at = now()
    where id = p_record_id and institution_id = p_institution_id
    returning * into v_record;
    if not found then
      raise exception 'The institution-scoped record was not found' using errcode = 'P0002';
    end if;
  end if;

  insert into public.institutional_record_reviews(record_id, institution_id, approval_status)
  values (v_record.id, v_record.institution_id, p_approval_status)
  on conflict (record_id) do update
    set approval_status = excluded.approval_status;

  return v_record;
end;
$function$;
revoke all on function public.save_institutional_record_with_review(
  uuid,uuid,text,text,text,text,text,text,text,text,date,date,numeric,numeric,jsonb,uuid
) from public, anon;
grant execute on function public.save_institutional_record_with_review(
  uuid,uuid,text,text,text,text,text,text,text,text,date,date,numeric,numeric,jsonb,uuid
) to authenticated;

-- The front-end must use the review relation for admin-only fields; portal SELECTs
-- on institutional_records cannot see the dropped columns through the Data API.
alter table public.institutional_records
  drop constraint if exists institutional_records_approval_status_check,
  drop constraint if exists institutional_records_reviewed_by_fkey,
  drop column approval_status,
  drop column reviewed_by,
  drop column reviewed_at,
  drop column review_notes;

commit;
