/**
 * Converts infrastructure/provider failures into task-appropriate messages.
 * Known application validation messages are preserved; SQL, RLS, HTTP and
 * provider diagnostics are never forwarded directly to ordinary users.
 */
export function userFacingError(error: unknown, fallback = 'Something went wrong. Please try again.') {
  const record = error && typeof error === 'object' ? error as Record<string, unknown> : undefined
  const message = typeof error === 'string'
    ? error.trim()
    : error instanceof Error
      ? error.message.trim()
      : typeof record?.message === 'string'
        ? record.message.trim()
        : ''
  const code = typeof record?.code === 'string' ? record.code.trim().toUpperCase() : ''
  const status = typeof record?.status === 'number' ? record.status : undefined
  const lower = message.toLowerCase()
  const combined = `${code} ${status ?? ''} ${lower}`

  if (!message && !code && status === undefined) return fallback
  if (status === 401) return 'Your secure session has expired. Sign in again to continue.'
  if (status === 403) return 'Your current role does not have permission to complete this action. Contact your institution administrator if you need access.'
  if (status !== undefined && status >= 500) return fallback

  if (/email not confirmed|email_not_confirmed/.test(combined)) {
    return 'Please verify your email using the confirmation link, then sign in again.'
  }
  if (/invalid login credentials|invalid_credentials|user not found|invalid password/.test(combined)) {
    return 'The email address or password is incorrect. Check your details and try again.'
  }
  if (/user already registered|email already exists|already been registered/.test(combined)) {
    return 'An account with this email already exists. Sign in or use a different email address.'
  }
  if (/rate limit|too many requests|over_email_send_rate_limit/.test(combined)) {
    return 'Too many attempts were made. Please wait a little and try again.'
  }
  if (/jwt expired|invalid jwt|session_not_found|refresh_token_not_found/.test(combined)) {
    return 'Your secure session has expired. Sign in again to continue.'
  }
  if (/failed to fetch|network request failed|networkerror|fetcherror|econnreset|enotfound|timeout|timed out|internet connection/.test(combined)) {
    return 'The internet connection was interrupted. Check your connection and try again.'
  }
  if (/23505|duplicate key|unique constraint|already exists/.test(combined)) {
    return 'A record with the same reference already exists. Check the register and use a unique value.'
  }
  if (/23503|foreign key constraint|violates foreign key/.test(combined)) {
    return 'A linked record could not be found. Refresh the related records and try again.'
  }
  if (/23502|not-null constraint|null value in column/.test(combined)) {
    return 'Some required information is missing. Review the form and try again.'
  }
  if (/23514|check constraint|invalid input syntax|22p02/.test(combined)) {
    return 'One or more values are not valid. Review the form and try again.'
  }
  if (/42501|\brls\b|row.level security|permission denied|not authorized|unauthorized|forbidden|\b403\b/.test(combined)) {
    return 'Your current role does not have permission to complete this action. Contact your institution administrator if you need access.'
  }
  if (/mime type|unsupported media type|content.type .*not supported/.test(combined)) {
    return 'This file type is not supported. Upload PDF, PNG, JPG, WebP, TXT, Word or Excel documents.'
  }
  if (/entitytoolarge|payload too large|file too large|\b413\b/.test(combined)) {
    return 'The file is larger than the allowed limit. Choose a smaller file and try again.'
  }
  if (/bucket not found/.test(combined)) {
    return 'Cloud file storage is not available for this institution. Please contact support.'
  }
  if (/objectnotfound|storage object not found|object not found/.test(combined)) {
    return 'This file is no longer available. Refresh the file list and try again.'
  }

  const technical = /\b(postgres|postgresql|postgrest|sqlstate|sql error|rest api|edge function|stack trace|internal server error|relation .* does not exist|column .* does not exist|schema cache|violates .* constraint|jwt|supabase|http 5\d\d|invalid api key)\b/i
  const hasProviderCode = /^(PGRST|23[0-9A-Z]{3}|22[0-9A-Z]{3}|42[0-9A-Z]{3}|5\d\d)/.test(code)
  const looksLikeStack = /\n\s*at\s+/.test(message)
  if (technical.test(message) || hasProviderCode || looksLikeStack || message.length > 220) return fallback

  // Keep concise, human-readable validation messages generated by the app.
  return message || fallback
}
